import { TakwimEntry, HolidayRecord, BidangType, JenisPengisian, PelaksanaanStatus } from '../types/takwim';
import { getAcademicWeekForDate, getDayStatus } from './calendar2027';

/**
 * Jana semua Perhimpunan Rasmi Mingguan (Sesi Pagi & Petang) untuk SETIAP HARI SELASA
 * sepanjang tahun persekolahan 2027 yang jatuh pada hari PdP (bukan cuti/hari kelepasan).
 */
export function generateTuesdayAssemblies(holidays: HolidayRecord[]): TakwimEntry[] {
  const assemblies: TakwimEntry[] = [];
  const now = new Date().toISOString();

  // 2027 calendar range: 1 Jan 2027 hingga 31 Dis 2027
  const startDate = new Date('2027-01-01T00:00:00');
  const endDate = new Date('2027-12-31T00:00:00');

  for (let d = new Date(startDate); d <= endDate; d.setDate(d.getDate() + 1)) {
    if (d.getDay() !== 2) continue; // 2 = Hari Selasa

    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    const dateStr = `${y}-${m}-${day}`;

    const weekInfo = getAcademicWeekForDate(dateStr);
    const dayStatus = getDayStatus(dateStr, holidays);

    // Hanya jika dalam blok akademik Kumpulan B dan merupakan hari persekolahan (PdP)
    if (!weekInfo.isTermHoliday && dayStatus.isPdPDay) {
      assemblies.push({
        id: `t-tue-${dateStr}`,
        tahun: 2027,
        bulan: d.getMonth() + 1,
        bidangUtama: 'Pengurusan dan Staf',
        unitUtama: 'Pentadbiran Sekolah',
        unitBersama: ['Hal Ehwal Murid', 'Kokurikulum'],
        jenisPengisian: 'Pelaksanaan Berkala',
        tajuk: 'Perhimpunan Rasmi Mingguan (Pagi: 07:00 - 07:30 | Petang: 12:40 - 01:10)',
        tajukPilihanBank: 'Perhimpunan Rasmi Mingguan (Pagi: 07:00 - 07:30 | Petang: 12:40 - 01:10)',
        adalahTajukSendiri: false,
        objektif:
          'Perhimpunan rasmi dwisesi SK Tudan bagi menyampaikan pesanan Guru Besar, laporan guru bertugas mingguan, lagu kebangsaan & negeri, serta amalan disiplin sekolah. Sesi Pagi: 07:00 - 07:30 pagi | Sesi Petang: 12:40 - 01:10 pm.',
        tarikhMula: dateStr,
        tarikhAkhir: dateStr,
        masaMula: '07:00',
        masaAkhir: '13:10',
        sepanjangHari: false,
        mingguAkademik: weekInfo.code,
        statusHari: dayStatus.statusLabel,
        tempat: 'Dataran Perhimpunan SK Tudan / Dewan Sri Tudan',
        sasaran: ['Semua Murid', 'Semua Guru & Staf'],
        penyelaras: 'Guru Bertugas Mingguan / Unit Disiplin',
        ajk: 'AJK Guru Bertugas Sesi Pagi & Sesi Petang',
        statusKelulusan: 'Diluluskan',
        diluluskanOleh: 'Pn. Hajah Fatimah Binti Ismail (Guru Besar)',
        tarikhKelulusan: '2026-12-30',
        statusPelaksanaan: dateStr <= '2027-03-01' ? 'Selesai' : 'Belum Bermula',
        catatan:
          'Wajib dihadiri semua murid dan guru: Sesi Pagi (07:00 - 07:30 pagi) & Sesi Petang (12:40 - 01:10 pm).',
        createdBy: 'u-gb',
        createdByName: 'Pn. Hajah Fatimah Binti Ismail',
        createdAt: now,
        updatedBy: 'u-gb',
        updatedByName: 'Pn. Hajah Fatimah Binti Ismail',
        updatedAt: now,
        revisionHistory: [
          {
            id: `rev-${dateStr}`,
            timestamp: now,
            action: 'Jadual Rasmi Berkala',
            userId: 'u-gb',
            userName: 'Pn. Hajah Fatimah Binti Ismail',
            details: 'Perhimpunan rasmi mingguan dwisesi setiap hari Selasa didaftarkan.',
          },
        ],
      });
    }
  }

  return assemblies;
}

