/**
 * Tukar senarai program PDF ke format penuh TakwimEntry
 */
export function generateFullPdfTakwimEntries(holidays: HolidayRecord[]): TakwimEntry[] {
  const now = new Date().toISOString();

  return RAW_PDF_2027_PROGRAMS.map((raw) => {
    const weekInfo = getAcademicWeekForDate(raw.tarikhMula);
    const dayStatus = getDayStatus(raw.tarikhMula, holidays);

    return {
      id: raw.id,
      tahun: 2027,
      bulan: raw.bulan,
      bidangUtama: raw.bidangUtama,
      unitUtama: raw.unitUtama,
      unitBersama: raw.unitBersama || [],
      jenisPengisian: raw.jenisPengisian,
      tajuk: raw.tajuk,
      tajukPilihanBank: raw.tajuk,
      adalahTajukSendiri: false,
      objektif: raw.objektif,
      tarikhMula: raw.tarikhMula,
      tarikhAkhir: raw.tarikhAkhir || raw.tarikhMula,
      masaMula: raw.masaMula || '08:00',
      masaAkhir: raw.masaAkhir || '12:00',
      sepanjangHari: false,
      mingguAkademik: weekInfo.code,
      statusHari: dayStatus.statusLabel,
      tempat: raw.tempat,
      sasaran: raw.sasaran,
      penyelaras: raw.penyelaras,
      ajk: raw.ajk || 'Jawatankuasa Unit Berkaitan',
      statusKelulusan: raw.statusKelulusan || 'Diluluskan',
      diluluskanOleh: 'Pn. Hajah Fatimah Binti Ismail (Guru Besar)',
      tarikhKelulusan: '2026-12-30',
      statusPelaksanaan: raw.statusPelaksanaan || 'Belum Bermula',
      createdBy: 'u-gb',
      createdByName: 'Pn. Hajah Fatimah Binti Ismail',
      createdAt: now,
      updatedBy: 'u-gb',
      updatedByName: 'Pn. Hajah Fatimah Binti Ismail',
      updatedAt: now,
      revisionHistory: [],
    };
  });
}

/**
 * Cantumkan semua aktiviti rasmi takwim PDF 2026 yang dipetakan ke 2027
 * bersama semua Perhimpunan Rasmi Hari Selasa untuk satu takwim lengkap sekolah.
 */
export function getFullTakwimSeed(holidays: HolidayRecord[]): TakwimEntry[] {
  const tuesdayAssemblies = generateTuesdayAssemblies(holidays);
  const pdfPrograms = generateFullPdfTakwimEntries(holidays);

  // Return combined list sorted by date ascending
  const combined = [...tuesdayAssemblies, ...pdfPrograms];
  combined.sort((a, b) => a.tarikhMula.localeCompare(b.tarikhMula) || a.masaMula.localeCompare(b.masaMula));
  return combined;
}
