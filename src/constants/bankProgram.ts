/**
 * Helper to get bank suggestions filtered by month and bidang
 */
export function getSuggestionsForMonthAndBidang(month: number, bidang?: BidangType): ProgramSuggestion[] {
  return BANK_PROGRAM_SUGGESTIONS.filter((s) => {
    const matchMonth = s.bulanCadangan.includes(month);
    const matchBidang = !bidang || s.bidang === bidang;
    return matchMonth && matchBidang;
  });
}
